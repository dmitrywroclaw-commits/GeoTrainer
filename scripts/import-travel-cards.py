TRANSLIT = str.maketrans(dict(zip(
    "абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
    ["a", "b", "v", "g", "d", "e", "e", "zh", "z", "i", "i", "k", "l", "m", "n", "o", "p", "r", "s", "t", "u", "f", "h", "ts", "ch", "sh", "shch", "", "y", "", "e", "yu", "ya"]
)))


def slug(value):
    value = unicodedata.normalize("NFKD", value.lower().translate(TRANSLIT))
    value = "".join(char for char in value if not unicodedata.combining(char))
    return re.sub(r"[^a-z0-9]+", "-", value).strip("-")


def rows(filename, expected_columns):
    lines = (DOCUMENTS / filename).read_text(encoding="utf-8").splitlines()
    parsed = []
    for line in lines:
        if re.match(r"^\|\s*\d+\s*\|", line):
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if len(cells) != expected_columns:
                raise ValueError(f"Unexpected number of columns: {line}")
            parsed.append(cells)
    return parsed


